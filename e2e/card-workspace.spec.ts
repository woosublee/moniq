test("search, month picker, keyboard tooltip and return from card detail", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/demo/entry");
  await page.goto("/cards?month=2026-02&tab=performance");
  const mark = page.getByRole("button", { name: /1구간 300,000원, 달성, 내 목표/ });
  await mark.focus();
  await expect(page.getByRole("tooltip")).toContainText("300,000원");
  expect(await mark.evaluate(element => getComputedStyle(element).outlineStyle)).not.toBe("none");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("tooltip")).toHaveCount(0);
  await page.keyboard.press("Tab");
  await expect(page.locator('[data-card-id="demo-everyday"]').getByRole("button", { name: /2구간 500,000원/ })).toBeFocused();
  await page.getByRole("textbox", { name: "카드 검색", exact: true }).fill("생활");
  await page.getByRole("button", { name: "검색", exact: true }).click();
  await expect(page.locator(".workspace-card")).toHaveCount(1);
  await expect(page).toHaveURL(/month=2026-02/);
  await page.locator(".workspace-card h2 a").click();
  await expect(page).toHaveURL(/cards\/demo-everyday\?month=2026-02/);
  await expect(page.getByRole("link", { name: "내 카드로 돌아가기" })).toBeVisible();
  await page.getByRole("link", { name: "내 카드로 돌아가기" }).click();
  await expect(page.locator(".workspace-card")).toHaveCount(1);
  await page.getByText("2026년 2월", { exact: true }).click();
  await page.getByLabel("조회할 월").fill("2026-01");
  await page.getByRole("button", { name: "이동", exact: true }).click();
  await expect(page).toHaveURL(/month=2026-01/);
  await page.goBack();
  await expect(page).toHaveURL(/month=2026-02/);
  await page.getByText("2026년 2월", { exact: true }).click();
  await expect(page.getByLabel("조회할 월")).toHaveValue("2026-02");
  await page.emulateMedia({ reducedMotion: "reduce", forcedColors: "active" });
  await page.goto("/cards?month=2026-02");
  await page.screenshot({ path: testInfo.outputPath("forced-colors-390.png"), fullPage: true });
  await expect(page.getByRole("meter").first()).toHaveAttribute("aria-valuenow", "381000");
});
