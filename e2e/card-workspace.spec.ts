import { expect, test } from "@playwright/test";

for (const width of [320, 390]) {
  test(`Task7 read-only transaction and card detail preserve canonical state at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 844 });
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto("/demo/entry");
    await expect(page).toHaveURL(/\/ledger\?month=2026-02$/);
    await page.goto("/cards?month=2026-02&tab=transactions&page=2");
    const before = page.url();
    const trigger = page.getByRole("button", { name: "거래 상세·수정", exact: true }).first();
    await trigger.click();
    const dialog = page.getByRole("dialog");
    await expect(dialog).toContainText("읽기 전용");
    await expect(dialog).toContainText("결제금액");
    await expect(dialog.locator("form")).toHaveCount(0);
    await expect(dialog.getByRole("button", { name: /저장|제외|취소 기록/ })).toHaveCount(0);
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`transaction-detail-${width}.png`) });
    await page.keyboard.press("Escape");
    await expect(dialog).toHaveCount(0);
    await expect(trigger).toBeFocused();
    expect(page.url()).toBe(before);
    await page.goto("/cards/demo-everyday?month=2026-02&tab=transactions&query=%EC%83%9D%ED%99%9C&card=demo-everyday");
    await expect(page.getByRole("heading", { name: "전월 총실적과 자료 상태" })).toBeVisible();
    await expect(page.getByRole("heading", { name: "목표 구간", exact: true })).toBeVisible();
    await expect(page.locator(".ledger-small-form")).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath(`card-detail-${width}.png`), fullPage: true });
    await page.getByRole("link", { name: "내 카드로 돌아가기", exact: true }).click();
    await expect(page).toHaveURL(/month=2026-02&tab=transactions&query=%EC%83%9D%ED%99%9C&card=demo-everyday$/);
    expect(errors).toEqual([]);
  });
}

